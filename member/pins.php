            <div>
                <span class="text-xs font-bold uppercase tracking-wider text-cyan-400">Affiliate Activation Tool</span>
                <h1 class="text-2xl sm:text-3xl font-extrabold text-white mt-1">E-PIN Generation & Inventory</h1>
                <p class="text-xs sm:text-sm text-slate-400 mt-1">
                    Use your earned wallet balance to generate registration PINs for onboarding new recruits.
                </p>
            </div>
            <div class="p-4 rounded-xl bg-slate-900/90 border border-slate-700/80 flex items-center space-x-4">
                <div>
                    <span class="text-[10px] uppercase font-bold text-slate-400 tracking-wider">Available Wallet Balance</span>
                    <div class="text-2xl font-black text-emerald-400">₹<?= number_format((float)$wallet['balance'], 2) ?></div>
                </div>
                <div class="w-10 h-10 rounded-xl bg-emerald-500/10 border border-emerald-500/30 flex items-center justify-center text-emerald-400">
                    <i class="fa-solid fa-wallet text-lg"></i>
                </div>
            </div>
        </div>
    </div>

    <?php if (!empty($error)): ?>
        <div class="p-4 rounded-xl bg-rose-950/70 border border-rose-500/40 text-rose-300 text-sm flex items-center space-x-2">
            <i class="fa-solid fa-circle-exclamation text-rose-400"></i>
            <span><?= e($error) ?></span>
        </div>
    <?php endif; ?>

    <?php if (!empty($success)): ?>
        <div class="p-4 rounded-xl bg-emerald-950/70 border border-emerald-500/40 text-emerald-300 text-sm flex items-center space-x-2">
            <i class="fa-solid fa-circle-check text-emerald-400"></i>
            <span><?= e($success) ?></span>
        </div>
    <?php endif; ?>

    <!-- Generate PIN Card -->
    <div class="glass-panel p-6 rounded-2xl">
        <h2 class="text-lg font-bold text-white flex items-center mb-4">
            <i class="fa-solid fa-plus-circle text-cyan-400 mr-2"></i> Generate New E-PIN via Wallet
        </h2>
        <form method="POST" action="/member/pins.php" class="grid grid-cols-1 md:grid-cols-3 gap-4 items-end">
            <input type="hidden" name="action" value="generate_pin">
            <div class="md:col-span-2">
                <label class="block text-xs font-semibold uppercase tracking-wider text-slate-300 mb-1">Select Membership Package</label>
                <select name="package_id" id="packageSelect" required class="w-full px-3.5 py-2.5 bg-slate-900 border border-slate-700 rounded-xl text-white text-sm focus:border-cyan-400 focus:outline-none">
                    <?php foreach ($packages as $pkg): ?>
                        <option value="<?= $pkg['id'] ?>" data-price="<?= (float)$pkg['price'] ?>">
                            <?= e($pkg['package_name']) ?> — ₹<?= number_format((float)$pkg['price'], 2) ?> (<?= strtoupper($pkg['type']) ?>)
                        </option>
                    <?php endforeach; ?>
                </select>
            </div>
            <div>
                <button type="submit" id="btnGenPin" class="w-full py-2.5 px-4 rounded-xl font-bold text-slate-950 glow-gold-btn transition shadow-md flex items-center justify-center space-x-2">
                    <i class="fa-solid fa-bolt"></i>
                    <span>Generate E-PIN</span>
                </button>
