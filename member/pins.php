<script>
function copyPin(code, btn) {
    navigator.clipboard.writeText(code).then(() => {
        const orig = btn.innerHTML;
        btn.innerHTML = '<i class="fa-solid fa-check text-emerald-400 mr-1"></i> Copied!';
        setTimeout(() => { btn.innerHTML = orig; }, 2000);
    });
}
</script>

