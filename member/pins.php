<?php
/**
 * Member E-PIN Manager
 * Members can generate PINs for any package if wallet has sufficient balance,
 * view their generated PINs, and copy them to share with prospective recruits.
 */
require_once __DIR__ . '/../config.php';
require_once __DIR__ . '/../includes/auth.php';
require_once __DIR__ . '/../includes/pin_engine.php';

requireMember();
$user = getCurrentUser();
$pdo = getDBConnection();

$error = '';
$success = '';

// Handle PIN generation
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['action']) && $_POST['action'] === 'generate_pin') {
    $packageId = (int)($_POST['package_id'] ?? 0);
    $result = generatePinByMember($pdo, (int)$user['id'], $packageId);
    if ($result['success']) {
        $success = $result['message'];
    } else {
        $error = $result['message'];
    }
}

// Fetch member wallet
$wStmt = $pdo->prepare("SELECT balance, total_earned, total_withdrawn FROM wallets WHERE user_id = ?");
$wStmt->execute([$user['id']]);
$wallet = $wStmt->fetch() ?: ['balance' => 0.00];

// Fetch active packages available for PIN generation
$pkgStmt = $pdo->query("SELECT id, package_name, price, type, description FROM packages WHERE is_active = 1 ORDER BY price ASC");
$packages = $pkgStmt->fetchAll();

// Fetch PINs generated by this user
$pinsStmt = $pdo->prepare("
    SELECT ep.id, ep.pin_code, ep.status, ep.created_at, ep.used_at,
           p.package_name, p.price, p.type AS package_type,
           u.username AS used_by_username, u.full_name AS used_by_name
    FROM e_pins ep
    JOIN packages p ON ep.package_id = p.id
    LEFT JOIN users u ON ep.used_by = u.id
    WHERE ep.generated_by = ?
    ORDER BY ep.id DESC
");
$pinsStmt->execute([$user['id']]);
$pins = $pinsStmt->fetchAll();

$pageTitle = 'My E-PIN Manager';
require_once __DIR__ . '/../includes/header.php';
?>

